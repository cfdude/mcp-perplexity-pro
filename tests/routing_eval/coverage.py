"""The offline coverage gate of the evaluation (routing-v2 task 2.6).

Reads ``data/routing_evidence.json``, the packaged matrix baseline and the labeled set, and
GENERATES ``acceptance/coverage.md`` (never hand-written): per task class, the eligible shortlist
models and the share of the class's prompts the selector (not the fallback) would choose. A class
is KEPT only with at least ``MIN_SHARE`` of its prompts chosen by the selector AND at least
``MIN_MODELS`` eligible models; every other class is EXCLUDED FROM SCORING (nothing is edited: not
the rules, not the prompt-set file, not the frozen hashes; the excluded class's prompts stay in
the file and run the fallback chain). With fewer than ``MIN_KEPT`` kept classes the file records
``evidence too thin: router cannot be evaluated`` and the work stops for the owner.

Run it::

    uv run python tests/routing_eval/coverage.py

The file is machine-read by ``kept_classes`` (the set tests and the harness) and ``assert_passed``
(the harness refuses to start on the failed outcome).
"""

from __future__ import annotations

import sys
from dataclasses import dataclass
from decimal import Decimal
from pathlib import Path
from typing import Any

from mcp_perplexity_pro import matrix as matrix_mod
from mcp_perplexity_pro import routing_evidence as ev
from mcp_perplexity_pro import routing_select as rs
from mcp_perplexity_pro.settings import ROUTER_MARGIN_DEFAULT

try:
    from routing_eval import promptset
except ModuleNotFoundError:  # run as a script: ``tests/`` is not on the path yet
    sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
    from routing_eval import promptset

MIN_SHARE = Decimal("0.75")
MIN_MODELS = 3
MIN_KEPT = 2
COVERAGE_PATH = promptset.ACCEPTANCE / "coverage.md"
THIN = "evidence too thin: router cannot be evaluated"
PASSED = "passed"


@dataclass(frozen=True)
class ClassCoverage:
    task_class: str
    eligible: tuple[str, ...]
    prompts: int
    router_chosen: int

    @property
    def share(self) -> Decimal:
        return Decimal(self.router_chosen) / self.prompts if self.prompts else Decimal(0)

    @property
    def kept(self) -> bool:
        return len(self.eligible) >= MIN_MODELS and self.share >= MIN_SHARE


@dataclass(frozen=True)
class Coverage:
    classes: tuple[ClassCoverage, ...]
    as_of: str

    @property
    def kept(self) -> tuple[str, ...]:
        return tuple(c.task_class for c in self.classes if c.kept)

    @property
    def excluded(self) -> tuple[str, ...]:
        return tuple(c.task_class for c in self.classes if not c.kept)

    @property
    def outcome(self) -> str:
        return PASSED if len(self.kept) >= MIN_KEPT else THIN


def compute(
    evidence: ev.Evidence,
    matrix: matrix_mod.Matrix,
    prompts: list[dict[str, Any]],
    margin: Decimal = ROUTER_MARGIN_DEFAULT,
) -> Coverage:
    """The coverage of each task class of ``evidence`` over the evaluation ``prompts``.

    A prompt counts as router-chosen when ``select`` (text only, tool ``ask``, the prompt's own
    tier) answers ``router`` rather than ``fallback``. A class absent from ``task_classes`` or
    with no benchmark has no eligible model and every prompt falls back."""
    rows = []
    for task_class in sorted({*evidence.task_classes, *promptset.CLASSES}):
        eligible = tuple(sorted(m for _, m in rs.eligible_models(task_class, evidence, matrix)))
        mine = [p for p in prompts if p["task"] == task_class]
        chosen = sum(
            rs.select(task_class, p["expected"], "ask", evidence, matrix, (), margin).selected_by
            == "router"
            for p in mine
        )
        rows.append(ClassCoverage(task_class, eligible, len(mine), chosen))
    return Coverage(tuple(rows), str(evidence.as_of))


def render(coverage: Coverage) -> str:
    lines = [
        "# Coverage gate (generated by `tests/routing_eval/coverage.py`; never edit by hand)",
        "",
        f"outcome: {coverage.outcome}",
        f"kept: {', '.join(coverage.kept) or 'none'}",
        f"excluded: {', '.join(coverage.excluded) or 'none'}",
        "",
        f"Rule: a class is kept with at least {int(MIN_SHARE * 100)} percent of its prompts "
        f"chosen by the selector (not the fallback) AND at least {MIN_MODELS} eligible shortlist "
        "models; "
        f"fewer than {MIN_KEPT} kept classes records `{THIN}`. An excluded class is excluded from "
        "scoring only: its prompts stay in the set and run the fallback chain, and nothing else is "
        "edited. A class that is not kept is out of every threshold of the evaluation.",
        "",
        f"Evidence `as_of` {coverage.as_of}.",
        "",
        "| Class | Eligible models | Prompts | Router-chosen | Share | Verdict |",
        "|---|---|---|---|---|---|",
    ]
    for c in coverage.classes:
        models = ", ".join(f"`{m}`" for m in c.eligible) or "none"
        verdict = "KEPT" if c.kept else "EXCLUDED"
        lines.append(
            f"| {c.task_class} | {len(c.eligible)}: {models} | {c.prompts} | {c.router_chosen} "
            f"| {int(c.share * 100)}% | {verdict} |"
        )
    if coverage.outcome != PASSED:
        lines += [
            "",
            f"**{THIN}**: the work stops here for the owner (shrink the classes, source "
            "more figures, or hold `routing-v2`); no evaluation spend occurs.",
        ]
    return "\n".join(lines) + "\n"


def generate(path: Path = COVERAGE_PATH) -> Coverage:
    """Compute the coverage of the packaged evidence and write ``path``."""
    coverage = compute(
        ev.load_packaged(),
        matrix_mod.load_baseline(),
        promptset.evaluation_prompts(),
    )
    path.write_text(render(coverage))
    return coverage


def _field(path: Path, name: str) -> str:
    for line in path.read_text().splitlines():
        if line.startswith(f"{name}: "):
            return line.split(": ", 1)[1].strip()
    raise ValueError(f"{path} has no `{name}:` line")


def kept_classes(path: Path = COVERAGE_PATH) -> tuple[str, ...]:
    """The classes the harness and the set tests score, from the generated file."""
    value = _field(path, "kept")
    return () if value == "none" else tuple(v.strip() for v in value.split(","))


def assert_passed(path: Path = COVERAGE_PATH) -> None:
    """The harness refuses to start on a recorded failed outcome (or a missing file)."""
    if not path.exists():
        raise RuntimeError(f"{path} does not exist: run tests/routing_eval/coverage.py first")
    outcome = _field(path, "outcome")
    if outcome != PASSED:
        raise RuntimeError(f"the coverage gate failed: {outcome}")


if __name__ == "__main__":
    result = generate()
    print(f"kept: {', '.join(result.kept) or 'none'}; outcome: {result.outcome}")
